def _load_dotenv():
    """Tiny .env reader (no extra dependency): copies KEY=VALUE lines from
    <repo root>/.env or backend/.env into os.environ without overriding
    anything already set in the real environment."""
    for candidate in (BASE_DIR.parent / ".env", BASE_DIR / ".env"):
        if not candidate.is_file():
            continue
        for raw in candidate.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            os.environ.setdefault(key.strip(), value.strip().strip("\"'"))


_load_dotenv()


def _env_list(name):
    return [item.strip() for item in os.environ.get(name, "").split(",") if item.strip()]


